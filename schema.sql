CREATE TABLE IF NOT EXISTS categories (id INTERGER PRIMARY KEY AUTOINCREMENT,
name TEXT NOT NULL,
icon_name TEXT
);

CREATE TABLE IF NOT EXISTS topics(id INTERGER PRIMARY KEY AUTOINCREMENT,
categories_id INTERGER NOT NULL, tittle TEXT NOT NULL,
summary TEXT, warning_note TEXT, FOREIGN KEY(category_id)REFERENCES categories(id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS steps (id INTERGER PRIMARY KEY AUTOINCREMENT,topic_id INTERGER NOT NULL,
step_number INTERGER NOT NULL, headline TEXT NOT NULL, details TEXT, FOREIGN Key(topic_id) REFERENCES categories(id) ON DELETE CASCADE)
